"""Recompute the two different 50-attempt quantities from retained backtest rows.

Run from any directory: python3 studies/pb-odds-backtest/audit-counts.py > audit.json
Requires the rows generated by run_all.sh; does not rerun the Monte Carlo.
"""
import hashlib
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def audit():
    results = json.loads((HERE / "results.json").read_text())
    versions = []
    for version, prefix in [("released_0.2.4", "released"), ("checkout_with_change", "fix")]:
        files = [HERE / "cache" / f"rows-{prefix}.{i}.json" for i in range(4)]
        rows = [row for path in files for row in json.loads(path.read_text())["rows"]]
        rows = [row for row in rows if row["y50"] is not None]
        if not rows or len({(row["file"], row["k"]) for row in rows}) != len(rows):
            raise ValueError(f"Empty or duplicate stopping points: {version}")
        for row in rows:
            if row["y50"] != int(row["beatCount50"] > 0):
                raise ValueError("Binary outcome disagrees with threshold count")
        probabilities = [1 - (1 - row["pOne"]) ** 50 for row in rows]
        n = len(rows)
        entry = {
            "version": version,
            "n": n,
            "meanForecast": sum(probabilities) / n,
            "observedWindows": sum(row["y50"] for row in rows),
            "observedRate": sum(row["y50"] for row in rows) / n,
            "expectedBelowFrozenPB": sum(50 * row["pOne"] for row in rows),
            "observedBelowFrozenPB": sum(row["beatCount50"] for row in rows),
            "brier": sum((p - row["y50"]) ** 2 for p, row in zip(probabilities, rows)) / n,
            "rowFiles": [
                {"path": str(path.relative_to(HERE)), "bytes": path.stat().st_size, "sha256": digest(path)}
                for path in files
            ],
        }
        recorded = results["versions"][version]["all"]["50"]
        if n != recorded["n"]:
            raise ValueError(f"Row count differs from recorded results: {version}")
        comparisons = [
            (entry["meanForecast"], recorded["mean_forecast"]),
            (entry["observedRate"], recorded["base_rate"]),
            (entry["brier"], recorded["brier"]["model"]),
            (entry["expectedBelowFrozenPB"], recorded["expected_pbs_per_attempt_next50"]),
            (entry["observedBelowFrozenPB"], recorded["observed_pbs_per_attempt_next50"]),
        ]
        if any(not math.isclose(a, b, rel_tol=1e-12, abs_tol=1e-12) for a, b in comparisons):
            raise ValueError(f"Recomputed quantities differ from recorded results: {version}")
        versions.append(entry)
    return {
        "scope": "Recomputed from retained historical rows; no Monte Carlo rerun or new calibration evidence.",
        "resultSha256": digest(HERE / "results.json"),
        "versions": versions,
    }


if __name__ == "__main__":
    print(json.dumps(audit(), indent=2))
