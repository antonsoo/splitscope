/**
 * Exports: a Markdown summary (for a Discord message, a PR, a wiki page)
 * and a PNG "share card" (for a stream overlay screenshot or a social
 * post). Both run entirely client-side — nothing is uploaded anywhere.
 */
import { bestRoute } from "../core/best-route.js";
import type { PbOddsResult } from "../core/montecarlo.js";
import { simulatePbOdds } from "../core/montecarlo.js";
import {
  pbTotal as computePbTotal,
  playtimeSummary,
  possibleTimeSave,
  resetAnalysis,
} from "../core/stats.js";
import { formatSeconds } from "../core/timespan.js";
import type { Run, TimingMethod } from "../core/types.js";
import { formatAttemptsRange, formatCount, formatHours, formatPercent } from "./format.js";

export interface ExportParams {
  readonly isSample?: boolean;
  readonly method: TimingMethod;
  readonly recentWindow: number;
  readonly simulations: number;
  readonly lookaheadAttempts: number;
}

/** Imported labels stay literal even in headings and Markdown tables. */
export function markdownText(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replace(/[\\`*_{}[\]()#+.!|~-]/g, "\\$&")
    .replace(/[\r\n]+/g, " ");
}

export function buildMarkdownSummary(run: Run, params: ExportParams): string {
  const pb = computePbTotal(run, params.method);
  const sob = bestRoute(run, params.method);
  const saves = possibleTimeSave(run, params.method)
    .map((save, i) => ({ name: run.segments[i]?.label ?? `Segment ${i + 1}`, save }))
    .filter((s): s is { name: string; save: number } => s.save !== null && s.save > 0)
    .sort((a, b) => b.save - a.save)
    .slice(0, 5);
  const reset = resetAnalysis(run);
  const playtime = playtimeSummary(run);
  const odds: PbOddsResult = simulatePbOdds(run, pb, {
    method: params.method,
    recentWindow: params.recentWindow,
    simulations: params.simulations,
    lookaheadAttempts: params.lookaheadAttempts,
  });

  const worst = [...reset.points].sort((a, b) => b.deaths - a.deaths)[0];

  const lines = [
    `# ${markdownText(run.gameName)} — ${markdownText(run.categoryName)}`,
    "",
    `Generated by [splitscope](https://antonsoo.github.io/splitscope/) · timing method: ${params.method} · ${formatCount(run.attempts.length)} attempts · ${playtime.attemptsMissingTimestamps === playtime.totalAttempts ? "playtime unavailable" : `${formatHours(playtime.totalPlaytimeSeconds)} played${playtime.attemptsMissingTimestamps ? " (subtotal)" : ""}`}`,
    "",
    params.isSample ? "**Synthetic sample — not a real speedrun.**\n" : null,
    "## Headline",
    "",
    `- **PB:** ${formatSeconds(pb)}`,
    `- **Sum of best:** ${sob.totalSeconds === null ? "Unavailable (no complete path through the saved times)" : formatSeconds(sob.totalSeconds)}`,
    `- **Individual golds added:** ${sob.goldSumSeconds === null ? "Incomplete" : formatSeconds(sob.goldSumSeconds)}`,
    `- **Total possible time save:** ${pb !== null && sob.totalSeconds !== null ? formatSeconds(pb - sob.totalSeconds) : "— (requires a PB and a complete recorded path)"}`,
    playtime.attemptsMissingTimestamps
      ? `- **Playtime coverage:** ${formatCount(playtime.totalAttempts - playtime.attemptsMissingTimestamps)} / ${formatCount(playtime.totalAttempts)} attempts have valid timestamps; the playtime above is a subtotal.`
      : null,
    `- **Finished attempts:** ${formatCount(reset.finishedAttempts)} / ${formatCount(reset.totalAttempts)} (${formatPercent(reset.totalAttempts ? reset.finishedAttempts / reset.totalAttempts : null)})`,
    worst && worst.deaths > 0
      ? `- **Where runs die most:** ${markdownText(worst.segmentName)} (${formatCount(worst.deaths)} resets)`
      : null,
    "",
    reset.unlocatedOutcomes
      ? `**Unknown outcomes:** ${reset.unlocatedOutcomes} attempts reach the final segment without an overall time; no reset location is assigned.`
      : null,
    "## Sum of best evidence",
    "",
    "A hypothetical combination of saved golds, PB spans and combined skipped-split times; not one attempt or a pace forecast. Combined savings cannot be assigned to an individual segment.",
    "",
    "| Segments | Time | Source |",
    "| --- | ---: | --- |",
    ...sob.legs.map(
      (leg) =>
        `| ${leg.from + 1}–${leg.to} | ${formatSeconds(leg.seconds)} | ${leg.source.kind === "gold" ? "Stored gold" : leg.source.kind === "personal-best" ? "PB split difference" : `History #${leg.source.attemptId}`} |`,
    ),
    "",
    "## Biggest individual time-save opportunities",
    "",
    "| Segment | Possible save |",
    "| --- | ---: |",
    ...saves.map((s) => `| ${markdownText(s.name)} | ${formatSeconds(s.save)} |`),
    "",
    "## PB odds (Monte Carlo)",
    "",
    pb === null
      ? "_No PB recorded for this timing method; PB odds are unavailable._"
      : odds.insufficientData
        ? `_${odds.unavailableReason}_`
        : [
            `- **P(next attempt beats PB):** ${formatPercent(odds.pbProbabilityPerAttempt, 2)} (95% CI ${formatPercent(odds.pbProbabilityPerAttemptCi[0], 2)}–${formatPercent(odds.pbProbabilityPerAttemptCi[1], 2)})`,
            `- **P(≥ 1 PB in next ${odds.lookaheadAttempts} attempts):** ${formatPercent(odds.probabilityAtLeastOnePb, 1)} (95% CI ${formatPercent(odds.probabilityAtLeastOnePbCi[0], 1)}–${formatPercent(odds.probabilityAtLeastOnePbCi[1], 1)})`,
            `- **Expected attempts to next PB:** ${odds.expectedAttemptsUntilPb === null ? "—" : formatCount(Math.round(odds.expectedAttemptsUntilPb))} (95% CI ${formatAttemptsRange(odds.expectedAttemptsUntilPbCi)})`,
            `- Based on ${formatCount(odds.simulations)} simulated attempts, resampled from the last ${odds.recentAttempts} attempts. The intervals cover simulation noise only. Assumes independent segments and a stationary recent-form window — see the app for full assumptions.`,
          ].join("\n"),
    "",
  ];

  return lines.filter((l): l is string => l !== null).join("\n");
}

const CARD_W = 1200;
const CARD_H = 630;

/** Renders the share card to a canvas and triggers a PNG download. */
export async function exportPngCard(run: Run, params: ExportParams): Promise<void> {
  const canvas = document.createElement("canvas");
  canvas.width = CARD_W;
  canvas.height = CARD_H;
  const ctx = canvas.getContext("2d");
  if (!ctx)
    throw new Error(
      "PNG export is unavailable in this browser. Download the Markdown summary instead.",
    );

  const pb = computePbTotal(run, params.method);
  const sob = bestRoute(run, params.method);
  const odds = simulatePbOdds(run, pb, {
    method: params.method,
    recentWindow: params.recentWindow,
    simulations: params.simulations,
    lookaheadAttempts: params.lookaheadAttempts,
  });

  // Background
  ctx.fillStyle = "#0b0e11";
  ctx.fillRect(0, 0, CARD_W, CARD_H);

  // Signature delta-rule bar
  const gradient = ctx.createLinearGradient(0, 0, CARD_W, 0);
  gradient.addColorStop(0, "#ff5c5c");
  gradient.addColorStop(0.5, "#f5c542");
  gradient.addColorStop(1, "#3ddc84");
  ctx.fillStyle = gradient;
  ctx.fillRect(0, 0, CARD_W, 6);

  ctx.fillStyle = "#808fa2";
  ctx.font = "600 20px monospace";
  ctx.fillText("SPLITSCOPE", 64, 76);

  ctx.fillStyle = "#8b95a1";
  ctx.font = "500 26px sans-serif";
  const title = `${run.gameName} — ${run.categoryName}`;
  ctx.fillText(title.length > 100 ? `${title.slice(0, 99)}…` : title, 64, 116, CARD_W - 128);

  ctx.fillStyle = "#808fa2";
  ctx.font = "500 16px monospace";
  ctx.fillText("PERSONAL BEST", 64, 200);
  ctx.fillStyle = "#f5c542";
  ctx.font = "700 96px monospace";
  ctx.fillText(formatSeconds(pb), 60, 280);

  const stats: [string, string][] = [
    ["SUM OF BEST", sob.totalSeconds !== null ? formatSeconds(sob.totalSeconds) : "Unavailable"],
    ["ATTEMPTS", formatCount(run.attempts.length)],
    [
      "P(PB NEXT ATTEMPT)",
      pb === null || odds.insufficientData ? "—" : formatPercent(odds.pbProbabilityPerAttempt, 2),
    ],
    [
      `P(≥1 PB / ${odds.lookaheadAttempts})`,
      pb === null || odds.insufficientData ? "—" : formatPercent(odds.probabilityAtLeastOnePb, 1),
    ],
  ];

  const colW = (CARD_W - 128) / stats.length;
  stats.forEach(([label, value], i) => {
    const cx = 64 + i * colW;
    ctx.fillStyle = "#808fa2";
    ctx.font = "600 14px monospace";
    ctx.fillText(label, cx, 400);
    ctx.fillStyle = "#e8ecef";
    ctx.font = "700 34px monospace";
    ctx.fillText(value, cx, 440, colW - 16);
    const interval =
      i === 2 ? odds.pbProbabilityPerAttemptCi : i === 3 ? odds.probabilityAtLeastOnePbCi : null;
    if (interval && interval[0] !== null && interval[1] !== null) {
      ctx.font = "500 13px monospace";
      ctx.fillStyle = "#8b95a1";
      ctx.fillText(
        `95% CI ${formatPercent(interval[0], 2)} – ${formatPercent(interval[1], 2)}`,
        cx,
        461,
        colW - 16,
      );
    }
  });

  ctx.strokeStyle = "#262d36";
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(64, 470);
  ctx.lineTo(CARD_W - 64, 470);
  ctx.stroke();

  ctx.fillStyle = "#808fa2";
  ctx.font = "500 15px monospace";
  ctx.fillText(`Timing: ${params.method}   ·   generated locally, nothing uploaded`, 64, 520);
  ctx.fillText(
    pb === null
      ? "No PB recorded: PB odds unavailable."
      : odds.insufficientData
        ? "Recent history is incomplete or ambiguous: PB odds unavailable."
        : `${formatCount(odds.simulations)} simulations · last ${odds.recentAttempts} attempts · intervals cover simulation noise only`,
    64,
    548,
    CARD_W - 128,
  );
  ctx.fillText(
    `antonsoo.github.io/splitscope${params.isSample ? " · SYNTHETIC SAMPLE" : ""}`,
    64,
    580,
  );

  const blob = await new Promise<Blob>((resolve, reject) => {
    canvas.toBlob(
      (value) =>
        value
          ? resolve(value)
          : reject(new Error("Could not generate the PNG. Download the Markdown summary instead.")),
      "image/png",
    );
  });
  downloadBlob(`splitscope-${run.gameName.replace(/[^a-z0-9]+/gi, "-").toLowerCase()}.png`, blob);
}

export function downloadText(filename: string, text: string, mime = "text/markdown"): void {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  downloadBlob(filename, blob);
}

function downloadBlob(filename: string, blob: Blob): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  // Revoking in the same task can cancel the download in some browsers.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
